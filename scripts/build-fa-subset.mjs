#!/usr/bin/env node
/**
 * Builds the Font Awesome subset in src/assets/fonts/fa-subset and
 * src/styles/_fontawesome-subset.scss. Run `npm run build:fa` after changing ICON_INVENTORY.
 */

import { fontawesomeSubset } from 'fontawesome-subset';
import { mkdir, writeFile, readFile, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

// NOTE: Keep this inventory synchronized with the `fa-*` classes used by components.
const ICON_INVENTORY = {
    solid: [
        'tools',
        'paper-plane',
        'wrench',
        'chevron-down',
        'chevron-right',
        'stethoscope',
        'file-invoice',
        'award',
        'laptop',
        'server',
        'network-wired',
        'headset',
        'database',
        'shield-alt',
        'user-check',
        'map-marker-alt',
        'bolt',
        'user-cog',
        'building',
        'laptop-medical',
        'arrow-right',
        'clock',
        'envelope',
        'check-circle',
        'spinner',
        'heart',
        'triangle-exclamation',
    ],
    brands: ['whatsapp', 'instagram', 'linkedin'],
};

// NOTE: These metadata codepoints keep the generated stylesheet independent of Font Awesome CSS.
const UNICODE = {
    tools: 'f7d9',
    'paper-plane': 'f1d8',
    wrench: 'f0ad',
    'chevron-down': 'f078',
    'chevron-right': 'f054',
    stethoscope: 'f0f1',
    'file-invoice': 'f570',
    award: 'f559',
    laptop: 'f109',
    server: 'f233',
    'network-wired': 'f6ff',
    headset: 'f590',
    database: 'f1c0',
    'shield-alt': 'f3ed',
    'user-check': 'f4fc',
    'map-marker-alt': 'f3c5',
    bolt: 'f0e7',
    'user-cog': 'f4fe',
    building: 'f1ad',
    'laptop-medical': 'f812',
    'arrow-right': 'f061',
    clock: 'f017',
    envelope: 'f0e0',
    'check-circle': 'f058',
    spinner: 'f110',
    heart: 'f004',
    'triangle-exclamation': 'f071',
    whatsapp: 'f232',
    instagram: 'f16d',
    linkedin: 'f08c',
};

const outFontDir = path.join(root, 'src', 'assets', 'fonts', 'fa-subset');
const outStyleFile = path.join(
    root,
    'src',
    'styles',
    '_fontawesome-subset.scss',
);

async function main() {
    if (existsSync(outFontDir)) {
        await rm(outFontDir, { recursive: true, force: true });
    }
    await mkdir(outFontDir, { recursive: true });

    console.log(
        `[fa-subset] generating subsets: solid=${ICON_INVENTORY.solid.length}, brands=${ICON_INVENTORY.brands.length}`,
    );

    await fontawesomeSubset(
        { solid: ICON_INVENTORY.solid, brands: ICON_INVENTORY.brands },
        outFontDir,
        { targetFormats: ['woff2'] },
    );

    const css = buildStylesheet();
    await writeFile(outStyleFile, css, 'utf8');

    console.log(`[fa-subset] wrote ${path.relative(root, outStyleFile)}`);
    console.log(`[fa-subset] wrote ${path.relative(root, outFontDir)}/*.woff2`);
}

function buildStylesheet() {
    const lines = [];
    lines.push('// WARNING: Generated by scripts/build-fa-subset.mjs; edit ICON_INVENTORY and regenerate instead.');
    lines.push('');
    lines.push('@font-face {');
    lines.push("    font-family: 'FA Solid';");
    lines.push('    font-style: normal;');
    lines.push('    font-weight: 900;');
    lines.push('    font-display: swap;');
    lines.push(
        "    src: url('/assets/fonts/fa-subset/fa-solid-900.woff2') format('woff2');",
    );
    lines.push('}');
    lines.push('');
    lines.push('@font-face {');
    lines.push("    font-family: 'FA Brands';");
    lines.push('    font-style: normal;');
    lines.push('    font-weight: 400;');
    lines.push('    font-display: swap;');
    lines.push(
        "    src: url('/assets/fonts/fa-subset/fa-brands-400.woff2') format('woff2');",
    );
    lines.push('}');
    lines.push('');
    lines.push('.fa,');
    lines.push('.fas,');
    lines.push('.fab {');
    lines.push('    display: inline-block;');
    lines.push('    font-style: normal;');
    lines.push('    font-variant: normal;');
    lines.push('    text-rendering: auto;');
    lines.push('    line-height: 1;');
    lines.push('    -webkit-font-smoothing: antialiased;');
    lines.push('}');
    lines.push('');
    lines.push('.fa, .fas {');
    lines.push("    font-family: 'FA Solid';");
    lines.push('    font-weight: 900;');
    lines.push('}');
    lines.push('');
    lines.push('.fab {');
    lines.push("    font-family: 'FA Brands';");
    lines.push('    font-weight: 400;');
    lines.push('}');
    lines.push('');
    for (const icon of ICON_INVENTORY.solid) {
        lines.push(`.fa-${icon}::before { content: '\\${UNICODE[icon]}'; }`);
    }
    for (const icon of ICON_INVENTORY.brands) {
        lines.push(`.fa-${icon}::before { content: '\\${UNICODE[icon]}'; }`);
    }
    lines.push('');
    lines.push('.fa-spin {');
    lines.push('    animation: fa-spin 2s linear infinite;');
    lines.push('}');
    lines.push('@keyframes fa-spin {');
    lines.push('    0%   { transform: rotate(0deg); }');
    lines.push('    100% { transform: rotate(360deg); }');
    lines.push('}');
    lines.push('');

    return lines.join('\n');
}

main().catch((err) => {
    console.error('[fa-subset] failed:', err);
    process.exit(1);
});
